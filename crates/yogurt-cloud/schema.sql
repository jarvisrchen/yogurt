-- Live meetings matching the query, newest first, optionally on one device, 25 from page_offset. `more` is true on every row when there were more after them.
-- Archived meetings match only with only_archived, and then nothing else does. only_starred and only_label narrow it as in yogurt_library, and only with only_device.
-- Quotes work, a leading minus excludes, and the last word matches as a prefix so a half-typed word finds its meeting.
-- snippet is null when the title matches, and otherwise a headline with the matched words wrapped in U+E000 and U+E001.
create or replace function public.yogurt_search(token text, query text, only_device uuid default null, page_offset int default 0, only_archived boolean default false,
  only_starred boolean default false, only_label text default null)
returns table (device_id uuid, meeting_id text, push_id bigint, started_at bigint, ended_at bigint, title text, snippet text, more boolean)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
declare
  cap constant int := 25;
  skip int := least(greatest(coalesce(page_offset, 0), 0), 10000);
  cfg constant regconfig := 'yogurt_private.yogurt_ts';
  lexeme constant text := '''([^'']|'''')*''';
  q text := coalesce(query, '');
  tsq tsquery;
  prefix boolean := false;
  opts text := format('StartSel=%s, StopSel=%s, MaxWords=14, MinWords=6, MaxFragments=1, ShortWord=0', chr(57344), chr(57345));
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  q := translate(q, E'“”‘’', '""' || chr(39) || chr(39));
  -- A dash with space or the edge on both sides, such as a pasted bullet or a spaced hyphen, separates words, and so does an en or em dash anywhere.
  q := regexp_replace(regexp_replace(q, '(^|\s)[-–—]+(?=\s|$)', '\1', 'g'), '[–—]', ' ', 'g');
  -- A pasted URL matches by its host and path.
  q := yogurt_private.yogurt_search_words(regexp_replace(q, 'https?://', '', 'gi'));
  -- An ICU collation leaves $ + < = > ^ ` | ~ out of [:punct:], so they are listed.
  if q ~ '[^[:space:][:punct:]$+<=>^`|~]$' then
    -- A half-typed hyphenated word matches as a phrase of its parts, so "follow-u" finds "follow-up" and "follow up" and nothing with the parts apart.
    -- A hyphen before a digit belongs to the token, as in ABC-123, and an excluded or quoted word, an email, a host, a URL, or a file name stays whole.
    if substring(q from '\S+$') !~ '^-|[@./"]' and substring(q from '\S+$') ~ '[[:alnum:]]-[[:alpha:]]' then
      q := regexp_replace(regexp_replace(q, '(\S+)$', '"\1"'), '([[:alnum:]])-(?=[[:alpha:]][^[:space:]]*$)', '\1 ', 'g');
    end if;
    prefix := true;
  end if;
  tsq := websearch_to_tsquery(cfg, q);
  -- A query with no word outside an exclusion returns nothing.
  if regexp_replace(tsq::text, '!\s*(\([^()]*\)|' || lexeme || ')', '', 'g') !~ '''' then return; end if;
  if prefix and tsq::text !~ ('!\s*' || lexeme || '$') then
    tsq := regexp_replace(tsq::text, '(' || lexeme || ')$', '\1:*')::tsquery;
  end if;
  return query
    with m as (
      select i.device_id, i.meeting_id, i.push_id, i.started_at, i.ended_at, i.title, i.doc,
             row_number() over (order by i.started_at desc, i.meeting_id, i.device_id) as rn
      from yogurt_private.yogurt_search_index i
      where i.user_id = auth.uid() and i.tsv @@ tsq and (only_device is null or i.device_id = only_device)
        -- Deleted, archived, starred, and labels are read from the latest version, so a push the index has not caught up to takes effect at once.
        and (select v.body is not null and v.archived = coalesce(only_archived, false)
                    and (only_device is null or ((not coalesce(only_starred, false) or v.starred) and (only_label is null or v.labels @> pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object('id', only_label)))))
             from public.yogurt_versions v
             where v.device_id = i.device_id and v.meeting_id = i.meeting_id order by v.push_id desc limit 1)
      order by i.started_at desc, i.meeting_id, i.device_id
      limit skip + cap + 1
    )
    select m.device_id, m.meeting_id, m.push_id, m.started_at, m.ended_at, m.title,
           case when to_tsvector(cfg, m.title) @@ tsq then null else ts_headline(cfg, m.doc, tsq, opts) end,
           (select count(*) from m) > skip + cap
    from m where m.rn > skip and m.rn <= skip + cap order by m.rn;
end $$;

-- The k live, unarchived meetings that best match a cross-meeting chat question, approximating the desktop's retrieval, with what the chat sends the LLM.
-- Terms are ORed as prefixes and ranked by ts_rank normalized by length, newest first on ties.
-- No terms, or terms that match nothing, means the newest meetings, so a recap such as "what did I decide last week" still has meetings to read.
-- from_ms and to_ms bound started_at as [from_ms, to_ms), and either may be null. k is clamped to 1..20.
-- Each row comes from the meeting's latest version, so an edit the index has not caught up to still answers with the edited text.
-- notes are the enhanced notes when present, else the user's. excerpt is at most 64 words of transcript around the terms, and empty without a match.
create or replace function public.yogurt_retrieve(token text, terms text[], from_ms bigint default null, to_ms bigint default null, k int default 6)
returns table (device_id uuid, meeting_id text, title text, started_at bigint, notes text, excerpt text)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
declare
  cfg constant regconfig := 'yogurt_private.yogurt_ts';
  opts constant text := 'StartSel="", StopSel="", MaxWords=64, MinWords=48, MaxFragments=1, ShortWord=0, FragmentDelimiter=" … "';
  n constant int := least(greatest(coalesce(k, 6), 1), 20);
  tsq tsquery;
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  -- Quoted, a term is text the parser splits as it splits the index, so no term is read as tsquery syntax. A backslash or a quote would end the quoting.
  select to_tsquery(cfg, string_agg(format('''%s'':*', w), ' | ')) into tsq
  from (select translate(t, E'\\''', '') as w from unnest(coalesce(terms, '{}')) t) s
  where w ~ '[^[:space:][:punct:]]';
  if numnode(tsq) = 0 then tsq := null; end if;
  if tsq is not null then
    return query
      with hit as (
        select i.device_id, i.meeting_id
        from yogurt_private.yogurt_search_index i
        where i.user_id = auth.uid() and i.tsv @@ tsq
          and (from_ms is null or i.started_at >= from_ms) and (to_ms is null or i.started_at < to_ms)
          and (select v.body is not null and not v.archived from public.yogurt_versions v
               where v.device_id = i.device_id and v.meeting_id = i.meeting_id order by v.push_id desc limit 1)
        order by ts_rank(i.tsv, tsq, 1) desc, i.started_at desc, i.meeting_id, i.device_id
        limit n
      )
      select h.device_id, h.meeting_id, r.title, r.started_at, r.notes,
             ts_headline(cfg, yogurt_private.yogurt_plain(yogurt_private.yogurt_transcript(r.body)), tsq, opts)
      from hit h cross join lateral yogurt_private.yogurt_chat_row(h.device_id, h.meeting_id) r;
    if found then return; end if;
  end if;
  return query
    select l.device_id, l.meeting_id, r.title, r.started_at, r.notes, ''
    from (
      select distinct on (v.device_id, v.meeting_id) v.device_id, v.meeting_id, v.body is not null and not v.archived as shown
      from public.yogurt_versions v
      where v.user_id = auth.uid()
      order by v.device_id, v.meeting_id, v.push_id desc
    ) l
    cross join lateral yogurt_private.yogurt_chat_row(l.device_id, l.meeting_id) r
    where l.shown
      and (from_ms is null or r.started_at >= from_ms) and (to_ms is null or r.started_at < to_ms)
    order by r.started_at desc, l.meeting_id, l.device_id
    limit n;
end $$;

