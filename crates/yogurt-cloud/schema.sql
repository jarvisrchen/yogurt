create index if not exists yogurt_search_index_tsv on yogurt_private.yogurt_search_index using gin (tsv);
alter table yogurt_private.yogurt_search_index enable row level security;

-- A purge or an account deletion removes the version, and the cascade removes its text. Rows left from before the constraint existed are removed first.
do $$ begin
  if not exists (select from pg_catalog.pg_constraint where conname = 'yogurt_search_index_version' and conrelid = 'yogurt_private.yogurt_search_index'::regclass) then
    delete from yogurt_private.yogurt_search_index i
    where not exists (select from public.yogurt_versions v where v.device_id = i.device_id and v.meeting_id = i.meeting_id and v.push_id = i.push_id);
    alter table yogurt_private.yogurt_search_index add constraint yogurt_search_index_version
      foreign key (device_id, meeting_id, push_id) references public.yogurt_versions on delete cascade;
  end if;
end $$;

create table if not exists yogurt_private.yogurt_meta (key text primary key, value text not null);
alter table yogurt_private.yogurt_meta enable row level security;

-- Plain words from markdown or editor HTML, in their original case and accents.
-- A transcript link's label is dropped whole, other editor tags are dropped alone, and text such as "latency<target" stays.
-- Markdown markers go only at a line or word boundary, so "2*3" and "api_key" keep their characters.
-- U+E000 and U+E001 are removed because the search headline uses them as markers.
-- The result is at most 400,000 bytes, so a tsvector built from it stays far below its 1 MB limit.
create or replace function yogurt_private.yogurt_plain(md text) returns text
language plpgsql immutable set search_path = '' as $$
declare
  t text := left(coalesce(md, ''), 400000);
begin
  t := regexp_replace(t, '<span\s[^<>]*data-transcript-link[^<>]*>[^<]*</span>', ' ', 'g');
  t := regexp_replace(t, '</?(span|br|p|div|b|i|u|em|strong|code|pre|ul|ol|li|a|h[1-6])\y[^<>]*>', ' ', 'g');
  t := regexp_replace(t, '!?\[([^\]]*)\]\([^)]*\)', '\1', 'g');
  t := regexp_replace(t, '^\s{0,3}(#{1,6}|>|[-*+]|[0-9]+\.)\s+', '', 'gn');
  t := regexp_replace(t, '(^|[\s(\[])(\*{1,3}|_{1,3}|~~)(\S)', '\1\3', 'g');
  t := regexp_replace(t, '(\S)(\*{1,3}|_{1,3}|~~)($|[\s.,;:!?)\]])', '\1\3', 'g');
  t := replace(t, '`', '');
  t := translate(t, chr(57344) || chr(57345), '');
  t := replace(replace(replace(replace(replace(replace(t, '&nbsp;', ' '), '&lt;', '<'), '&gt;', '>'), '&quot;', '"'), '&#39;', ''''), '&amp;', '&');
  t := btrim(regexp_replace(t, '\s+', ' ', 'g'));
  while octet_length(t) > 400000 loop
    t := left(t, length(t) * 3 / 4);
  end loop;
  return t;
end $$;

-- Notes, enhanced notes, and each transcript segment of a pushed meeting. transcript_json is a JSON string inside the body, and a malformed one counts as no transcript.
create or replace function yogurt_private.yogurt_search_doc(body jsonb) returns text
language plpgsql stable set search_path = '' as $$
declare
  transcript text;
begin
  begin
    select string_agg(s ->> 'text', ' ') into transcript
    from jsonb_array_elements((body #>> '{meeting,transcript_json}')::jsonb) s;
  exception when others then
    transcript := null;
  end;
  return yogurt_private.yogurt_plain(concat_ws(E'\n', body #>> '{meeting,notes_md}', body #>> '{meeting,enriched_md}', transcript));
end $$;

-- A JSON number as milliseconds, or null when it is missing, not a number, or too large for a bigint.
create or replace function yogurt_private.yogurt_ms(j jsonb) returns bigint
language sql immutable set search_path = '' as $$
  select case when jsonb_typeof(j) = 'number' and (j #>> '{}')::numeric between -9000000000000000000 and 9000000000000000000
    then round((j #>> '{}')::numeric)::bigint end
$$;

-- Indexes one live version, and never replaces a newer push with an older one.
-- A version whose text cannot be built is stored with its title and no tsvector, so it never forces repeated work.
create or replace function yogurt_private.yogurt_search_put(uid uuid, device uuid, meeting text, push bigint, body jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare
  ttl text := left(coalesce(body #>> '{meeting,title}', ''), 1000);
  d text := '';
  v tsvector;
begin
  begin
    d := yogurt_private.yogurt_search_doc(body);
    v := to_tsvector('yogurt_private.yogurt_ts', ttl) || to_tsvector('yogurt_private.yogurt_ts', d);
  exception when others then
    d := '';
    v := null;
  end;
  insert into yogurt_private.yogurt_search_index as i (device_id, meeting_id, user_id, push_id, started_at, ended_at, title, doc, tsv)
  values (device, meeting, uid, push, coalesce(yogurt_private.yogurt_ms(body #> '{meeting,started_at}'), 0), yogurt_private.yogurt_ms(body #> '{meeting,ended_at}'), ttl, d, v)
  on conflict (device_id, meeting_id) do update set
    user_id = excluded.user_id, push_id = excluded.push_id, started_at = excluded.started_at, ended_at = excluded.ended_at,
    title = excluded.title, doc = excluded.doc, tsv = excluded.tsv
  where excluded.push_id >= i.push_id;
end $$;

-- A laptop's insert must never fail because of search, so every error here is swallowed and the next deploy's ensure repairs the row.
-- A version that a later push already replaced is ignored. Triggers do not check EXECUTE when they fire, so authenticated needs no grant on these functions.
create or replace function yogurt_private.yogurt_search_sync() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if exists (select from public.yogurt_versions n where n.device_id = new.device_id and n.meeting_id = new.meeting_id and n.push_id > new.push_id) then
    return null;
  end if;
  if new.body is null then
    delete from yogurt_private.yogurt_search_index where device_id = new.device_id and meeting_id = new.meeting_id;
  else
    perform yogurt_private.yogurt_search_put(new.user_id, new.device_id, new.meeting_id, new.push_id, new.body);
  end if;
  return null;
exception when others then
  return null;
end $$;

drop trigger if exists yogurt_search_sync on public.yogurt_versions;
create trigger yogurt_search_sync after insert on public.yogurt_versions
  for each row execute function yogurt_private.yogurt_search_sync();

-- A hash of everything that decides what the index holds: the text-search configuration and its dictionaries, the unaccent version, the table's columns, and the functions that build and maintain rows.
create or replace function yogurt_private.yogurt_search_signature() returns text
language sql stable security definer set search_path = '' as $$
  select md5(concat_ws(E'\n',
    (select extversion from pg_catalog.pg_extension where extname = 'unaccent'),
    (select string_agg(m.maptokentype || ':' || m.mapseqno || ':' || m.mapdict::regdictionary::text, ',' order by m.maptokentype, m.mapseqno)
      from pg_catalog.pg_ts_config_map m where m.mapcfg = 'yogurt_private.yogurt_ts'::regconfig),
    (select string_agg(a.attname || ' ' || a.atttypid::regtype::text, ',' order by a.attnum) from pg_catalog.pg_attribute a
      where a.attrelid = 'yogurt_private.yogurt_search_index'::regclass and a.attnum > 0 and not a.attisdropped),
    (select string_agg(pg_catalog.pg_get_functiondef(p.oid), E'\n' order by p.proname) from pg_catalog.pg_proc p
      where p.pronamespace = 'yogurt_private'::regnamespace
        and p.proname in ('yogurt_plain', 'yogurt_search_doc', 'yogurt_ms', 'yogurt_search_put', 'yogurt_search_sync'))))
$$;

-- Brings the index in line with the latest live version of each meeting: it deletes rows whose version was replaced or removed, and writes rows that are missing or outdated.
-- When the signature changed it rewrites every row. It never truncates, takes only row locks on the index, and runs outside the schema transaction, so a long refill does not hold up a push.
-- Returns whether it wrote anything.
create or replace function yogurt_private.yogurt_search_ensure() returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  sig text := yogurt_private.yogurt_search_signature();
  changed boolean := (select value from yogurt_private.yogurt_meta where key = 'search_signature') is distinct from sig;
  written bigint := 0;
  l record;
begin
  delete from yogurt_private.yogurt_search_index i
  where not exists (select from public.yogurt_versions v where v.device_id = i.device_id and v.meeting_id = i.meeting_id and v.push_id = i.push_id and v.body is not null)
     or exists (select from public.yogurt_versions n where n.device_id = i.device_id and n.meeting_id = i.meeting_id and n.push_id > i.push_id);
  for l in
    select v.user_id, v.device_id, v.meeting_id, v.push_id, v.body
    from (select x.device_id, x.meeting_id, max(x.push_id) as push_id from public.yogurt_versions x group by x.device_id, x.meeting_id) latest
    join public.yogurt_versions v using (device_id, meeting_id, push_id)
    left join yogurt_private.yogurt_search_index i using (device_id, meeting_id)
    where v.body is not null and (changed or i.push_id is distinct from v.push_id)
  loop
    begin
      perform yogurt_private.yogurt_search_put(l.user_id, l.device_id, l.meeting_id, l.push_id, l.body);
      written := written + 1;
    exception when others then
      null;
    end;
  end loop;
  insert into yogurt_private.yogurt_meta (key, value) values ('search_signature', sig)
  on conflict (key) do update set value = excluded.value;
  return written > 0;
end $$;

-- RPCs

create or replace function public.yogurt_status() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  o public.yogurt_owner;
  mine boolean := yogurt_private.yogurt_is_owner();
begin
  select * into o from public.yogurt_owner;
  return jsonb_build_object(
    'owner_email_set', found,
    'is_owner', mine,
    'passcode_set', mine and o.passcode_hash is not null,
    'passcode_length', case when mine then o.passcode_length end,
    'locked_until', case when mine and o.locked_until > now() then o.locked_until end
  );
end $$;

-- Five consecutive wrong tries across unlock and set_passcode lock both for 15 minutes, doubling each time up to 2^10 times, until a correct passcode resets it.
-- Returns false for a wrong old passcode or during a lockout. A raised error would roll back the failure count.
create or replace function public.yogurt_set_passcode(new_passcode text, old_passcode text default null) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  o public.yogurt_owner;
begin
  perform yogurt_private.yogurt_require_owner();
  if new_passcode is null or new_passcode !~ '^([0-9]{4}|[0-9]{6})$' then
    raise exception 'passcode must be 4 or 6 digits' using errcode = '22023';
  end if;
  select * into o from public.yogurt_owner for update;
  if o.locked_until > now() then return false; end if;
  if o.passcode_hash is not null
     and (old_passcode is null or extensions.crypt(old_passcode, o.passcode_hash) <> o.passcode_hash) then
    perform yogurt_private.yogurt_note_failure();
    return false;
  end if;
  update public.yogurt_owner
  set passcode_hash = extensions.crypt(new_passcode, extensions.gen_salt('bf')), passcode_length = length(new_passcode), failed_attempts = 0, consecutive_lockouts = 0, locked_until = null
  where id;
  delete from public.yogurt_browsers where true;
  return true;
end $$;

-- Returns null on a wrong passcode, during a lockout, or before a passcode exists. It never raises for those, so the failure count commits.
create or replace function public.yogurt_unlock(passcode text, remember boolean default false, label text default '') returns text
language plpgsql security definer set search_path = '' as $$
declare
  o public.yogurt_owner;
  token text;
begin
  perform yogurt_private.yogurt_require_owner();
  select * into o from public.yogurt_owner for update;
  if o.passcode_hash is null or o.locked_until > now() then return null; end if;
  if passcode is null or extensions.crypt(passcode, o.passcode_hash) <> o.passcode_hash then
    perform yogurt_private.yogurt_note_failure();
    return null;
  end if;
  update public.yogurt_owner set passcode_length = length(passcode), failed_attempts = 0, consecutive_lockouts = 0, locked_until = null where id;
  delete from public.yogurt_browsers where expires_at < now();
  token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.yogurt_browsers (token_hash, label, expires_at)
  values (
    sha256(convert_to(token, 'UTF8')),
    left(coalesce(label, ''), 100),
    now() + case when coalesce(remember, false) then interval '90 days' else interval '12 hours' end
  );
  return token;
end $$;

create or replace function public.yogurt_lock(token text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  perform yogurt_private.yogurt_require_owner();
  delete from public.yogurt_browsers where token_hash = sha256(convert_to(coalesce(token, ''), 'UTF8'));
  return found;
end $$;

create or replace function public.yogurt_forget_browser(token text, browser_id bigint) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  delete from public.yogurt_browsers where id = browser_id;
  return found;
end $$;

create or replace function public.yogurt_browsers(token text)
returns table (id bigint, label text, created_at timestamptz, expires_at timestamptz, last_used_at timestamptz, current boolean)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
declare
  me bigint;
begin
  perform yogurt_private.yogurt_require_owner();
  me := yogurt_private.yogurt_check_token(token);
  return query
    select b.id, b.label, b.created_at, b.expires_at, b.last_used_at, b.id = me
    from public.yogurt_browsers b where b.expires_at > now() order by b.id;
end $$;

create or replace function public.yogurt_start_push(device_id uuid) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  new_id bigint;
begin
  perform yogurt_private.yogurt_require_owner();
  if not exists (select from public.yogurt_owner where passcode_hash is not null) then
    raise exception 'choose a passcode in the webapp first' using errcode = 'PT412';
  end if;
  if not yogurt_private.yogurt_owns_device($1) then
    raise exception 'unknown device' using errcode = 'PT404';
  end if;
  insert into public.yogurt_pushes (device_id) values ($1) returning id into new_id;
  return new_id;
end $$;

create or replace function public.yogurt_device_meetings(device_id uuid) returns setof text
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  if not yogurt_private.yogurt_owns_device($1) then
    raise exception 'unknown device' using errcode = 'PT404';
  end if;
  return query
    select l.meeting_id from (
      select distinct on (v.meeting_id) v.meeting_id, v.body
      from public.yogurt_versions v
      where v.device_id = $1 and v.user_id = auth.uid()
      order by v.meeting_id, v.push_id desc
    ) l
    where l.body is not null order by l.meeting_id;
end $$;

-- The latest version of each live meeting per device at or before at_push, or now when null.
create or replace function public.yogurt_library(token text, at_push bigint default null)
returns table (device_id uuid, push_id bigint, pushed_at timestamptz, meeting_id text, body jsonb)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  return query
    select l.device_id, l.push_id, l.pushed_at, l.meeting_id, l.body from (
      select distinct on (v.device_id, v.meeting_id) v.device_id, v.push_id, p.pushed_at, v.meeting_id, v.body
      from public.yogurt_versions v join public.yogurt_pushes p on p.id = v.push_id
      where v.user_id = auth.uid() and (at_push is null or v.push_id <= at_push)
      order by v.device_id, v.meeting_id, v.push_id desc
    ) l
    where l.body is not null order by l.meeting_id, l.device_id;
end $$;

-- A signature from an earlier draft would make a call without the extra argument ambiguous.
drop function if exists public.yogurt_search(text, text, uuid, int);

-- Live meetings matching the query, newest first, optionally on one device, at most 25. `more` is true on every row when there were more.
-- Quotes work, a leading minus excludes, and the last word matches as a prefix so a half-typed word finds its meeting.
-- snippet is null when the title matches, and otherwise a headline with the matched words wrapped in U+E000 and U+E001.
create or replace function public.yogurt_search(token text, query text, only_device uuid default null)
returns table (device_id uuid, meeting_id text, push_id bigint, started_at bigint, ended_at bigint, title text, snippet text, more boolean)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
declare
  cap constant int := 25;
  cfg constant regconfig := 'yogurt_private.yogurt_ts';
  q text := coalesce(query, '');
  tsq tsquery;
  prefix boolean := false;
  opts text := format('StartSel=%s, StopSel=%s, MaxWords=14, MinWords=6, MaxFragments=1, ShortWord=0', chr(57344), chr(57345));
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  q := translate(q, E'“”‘’', '""' || chr(39) || chr(39));
  -- A spaced or long dash is punctuation, not a minus, and a pasted URL matches by its words.
  q := regexp_replace(regexp_replace(q, '\s[-–—]+\s|[–—]', ' ', 'g'), 'https?://', '', 'gi');
  if q ~ '[^[:space:][:punct:]]$' then
    -- A half-typed hyphenated word needs its parts, but a hyphen before a digit belongs to the token, as in ABC-123.
    q := regexp_replace(q, '([[:alnum:]])-(?=[[:alpha:]][^[:space:]]*$)', '\1 ', 'g');
    prefix := true;
  end if;
  tsq := websearch_to_tsquery(cfg, q);
  -- A query with no word outside an exclusion returns nothing.
  if numnode(tsq) = 0 or regexp_replace(tsq::text, '!\s*(\([^()]*\)|''([^'']|'''')*'')', '', 'g') !~ '''' then return; end if;
  if prefix and tsq::text !~ '!\s*''([^'']|'''')*''$' then
    begin
      tsq := regexp_replace(tsq::text, '(''([^'']|'''')*'')$', '\1:*')::tsquery;
    exception when others then null;
    end;
  end if;
  return query
    with m as (
      select i.device_id, i.meeting_id, i.push_id, i.started_at, i.ended_at, i.title, i.doc,
             row_number() over (order by i.started_at desc, i.meeting_id, i.device_id) as rn
      from yogurt_private.yogurt_search_index i
      where i.user_id = auth.uid() and i.tsv @@ tsq and (only_device is null or i.device_id = only_device)
      order by i.started_at desc, i.meeting_id, i.device_id
      limit cap + 1
    )
    select m.device_id, m.meeting_id, m.push_id, m.started_at, m.ended_at, m.title,
           case when to_tsvector(cfg, m.title) @@ tsq then null else ts_headline(cfg, m.doc, tsq, opts) end,
           (select count(*) from m) > cap
    from m where m.rn <= cap order by m.rn;
end $$;

create or replace function public.yogurt_history(token text)
returns table (push_id bigint, device_id uuid, device_name text, pushed_at timestamptz, changed bigint, deleted bigint)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  return query
    select p.id, p.device_id, d.name, p.pushed_at,
           count(v.body), count(*) filter (where v.body is null)
    from public.yogurt_pushes p
    join public.yogurt_versions v on v.push_id = p.id
    join public.yogurt_devices d on d.id = p.device_id
    where p.user_id = auth.uid()
    group by p.id, d.name
    order by p.id desc;
end $$;

create or replace function public.yogurt_device_list(token text)
returns table (id uuid, name text, created_at timestamptz)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  return query
    select d.id, d.name, d.created_at from public.yogurt_devices d where d.user_id = auth.uid() order by d.created_at, d.id;
end $$;

-- Row security backs the grants up.
alter table public.yogurt_owner    enable row level security;
alter table public.yogurt_browsers enable row level security;
alter table public.yogurt_devices  enable row level security;
alter table public.yogurt_pushes   enable row level security;
alter table public.yogurt_versions enable row level security;

-- Only devices and versions are insertable. Pushes start through yogurt_start_push, because insert ... returning needs select.
drop policy if exists add on public.yogurt_devices;
create policy add on public.yogurt_devices for insert to authenticated
  with check (user_id = (select auth.uid()) and (select yogurt_private.yogurt_is_owner()));
drop policy if exists add on public.yogurt_versions;
create policy add on public.yogurt_versions for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and (select yogurt_private.yogurt_is_owner())
    and (select yogurt_private.yogurt_push_open(push_id, device_id))
  );

-- Grants are explicit because Supabase no longer grants new public tables to the API roles, and TRUNCATE is outside RLS.
revoke all on public.yogurt_owner, public.yogurt_browsers, public.yogurt_devices, public.yogurt_pushes, public.yogurt_versions
  from public, anon, authenticated;
revoke all on yogurt_private.yogurt_search_index, yogurt_private.yogurt_meta from public, anon, authenticated;
revoke all on sequence public.yogurt_browsers_id_seq, public.yogurt_pushes_id_seq from public, anon, authenticated;
grant insert (id, name) on public.yogurt_devices to authenticated;
grant insert (meeting_id, push_id, device_id, body) on public.yogurt_versions to authenticated;

-- Execute is revoked everywhere first, so a new or dropped function is never granted by default.
do $$
declare
  f regprocedure;
begin
  for f in select p.oid::regprocedure from pg_proc p
           where p.pronamespace = 'public'::regnamespace and p.proname like 'yogurt\_%' loop
    execute format('revoke execute on function %s from public, anon, authenticated', f);
  end loop;
end $$;
revoke all on schema yogurt_private from public, anon;
revoke execute on all functions in schema yogurt_private from public, anon, authenticated;

grant execute on function
  public.yogurt_status(),
  public.yogurt_set_passcode(text, text),
  public.yogurt_unlock(text, boolean, text),
  public.yogurt_lock(text),
  public.yogurt_forget_browser(text, bigint),
  public.yogurt_browsers(text),
  public.yogurt_start_push(uuid),
  public.yogurt_device_meetings(uuid),
  public.yogurt_library(text, bigint),
  public.yogurt_search(text, text, uuid),
  public.yogurt_history(text),
  public.yogurt_device_list(text)
to authenticated;

-- The insert policies run as the caller, so the three policy helpers are the only private functions it may execute.
grant usage on schema yogurt_private to authenticated;
grant execute on function
  yogurt_private.yogurt_is_owner(),
  yogurt_private.yogurt_owns_device(uuid),
  yogurt_private.yogurt_push_open(bigint, uuid)
to authenticated;

