create table if not exists public.yogurt_owner (
  id              boolean primary key default true check (id),
  email           text not null,
  user_id         uuid references auth.users on delete set null,
  passcode_hash   text,
  failed_attempts int not null default 0,
  consecutive_lockouts int not null default 0,
  locked_until    timestamptz
);

-- The PIN's digit count, so the webapp can draw as many boxes. Set with the PIN, and backfilled by the next correct unlock for a PIN set before this column existed.
alter table public.yogurt_owner add column if not exists passcode_length smallint;

create table if not exists public.yogurt_browsers (
  id           bigint generated always as identity primary key,
  token_hash   bytea not null unique,  -- sha256 of the token, which is never stored
  label        text not null,
  created_at   timestamptz not null default now(),
  expires_at   timestamptz not null,
  last_used_at timestamptz not null default now()
);

create table if not exists public.yogurt_devices (
  id         uuid primary key,  -- generated by the laptop
  user_id    uuid not null default auth.uid() references auth.users on delete cascade,
  name       text not null,
  created_at timestamptz not null default now()
);

-- Ids are global across devices, so "as of push N" covers every device at that moment.
create table if not exists public.yogurt_pushes (
  id        bigint generated always as identity primary key,
  device_id uuid not null references public.yogurt_devices,
  user_id   uuid not null default auth.uid() references auth.users on delete cascade,
  pushed_at timestamptz not null default now()
);

-- One row per meeting a push changed. A null body marks the meeting deleted on that device in that push.
create table if not exists public.yogurt_versions (
  meeting_id text   not null,  -- the local ULID
  push_id    bigint not null references public.yogurt_pushes,
  device_id  uuid   not null references public.yogurt_devices,
  user_id    uuid   not null default auth.uid() references auth.users on delete cascade,
  body       jsonb,
  primary key (device_id, meeting_id, push_id)
);
create index if not exists yogurt_versions_push_id on public.yogurt_versions (push_id);
-- Whether the Mac had archived or starred the meeting, and its labels, kept beside the body so reads filter on them without detoasting every version.
alter table public.yogurt_versions add column if not exists archived boolean generated always as (body -> 'meeting' ->> 'archived_at' is not null) stored;
alter table public.yogurt_versions
  add column if not exists starred boolean generated always as (coalesce(body -> 'meeting' -> 'starred' = 'true'::jsonb, false)) stored,
  add column if not exists labels jsonb generated always as (body -> 'meeting' -> 'labels') stored;

