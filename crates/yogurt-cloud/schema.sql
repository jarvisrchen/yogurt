-- Yogurt Cloud schema. Idempotent: the build applies it on every production deploy.
-- Clients get no select on any table. Reads go through the RPCs below, which need the owner and a browser token.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create schema if not exists yogurt_private;

do $$ begin
  -- Tables from the earlier encrypted schema are dropped when present.
  if exists (select from information_schema.columns where table_schema = 'public' and table_name = 'yogurt_versions' and column_name = 'ct') then
    drop view if exists public.yogurt_push_log;
    drop function if exists public.yogurt_as_of(bigint);
    drop table if exists public.yogurt_versions, public.yogurt_pushes, public.yogurt_devices, public.yogurt_keyring cascade;
  end if;
end $$;

create table if not exists public.yogurt_owner (
  id              boolean primary key default true check (id),
  email           text not null,
  user_id         uuid references auth.users on delete set null,
  passcode_hash   text,
  failed_attempts int not null default 0,
  consecutive_lockouts int not null default 0,
  locked_until    timestamptz
);

create table if not exists public.yogurt_browsers (
  id           bigint generated always as identity primary key,
  token_hash   bytea not null unique,  -- sha256 of the token, which is never stored
  label        text not null,
  created_at   timestamptz not null default now(),
  expires_at   timestamptz not null,
  last_used_at timestamptz not null default now()
);

create table if not exists public.yogurt_devices (
  id         uuid primary key,  -- generated by the laptop
  user_id    uuid not null default auth.uid() references auth.users on delete cascade,
  name       text not null,
  created_at timestamptz not null default now()
);

-- Ids are global across devices, so "as of push N" covers every device at that moment.
create table if not exists public.yogurt_pushes (
  id        bigint generated always as identity primary key,
  device_id uuid not null references public.yogurt_devices,
  user_id   uuid not null default auth.uid() references auth.users on delete cascade,
  pushed_at timestamptz not null default now()
);

-- One row per meeting a push changed. A null body marks the meeting deleted on that device in that push.
create table if not exists public.yogurt_versions (
  meeting_id text   not null,  -- the local ULID
  push_id    bigint not null references public.yogurt_pushes,
  device_id  uuid   not null references public.yogurt_devices,
  user_id    uuid   not null default auth.uid() references auth.users on delete cascade,
  body       jsonb,
  primary key (device_id, meeting_id, push_id)
);
create index if not exists yogurt_versions_push_id on public.yogurt_versions (push_id);

-- The helpers used to live in public, and the old insert policies depend on them.
drop policy if exists add on public.yogurt_devices;
drop policy if exists add on public.yogurt_versions;
drop function if exists public.yogurt_is_owner(), public.yogurt_owns_device(uuid), public.yogurt_push_open(bigint, uuid),
  public.yogurt_note_failure(), public.yogurt_check_token(text), public.yogurt_require_owner();

-- PostgREST runs with pg-safeupdate, so every update and delete below has a where clause.
-- Helpers live in yogurt_private, which PostgREST does not expose. The definer functions below run them as the table owner.

create or replace function yogurt_private.yogurt_note_failure() returns void
language sql security definer set search_path = '' as $$
  update public.yogurt_owner set
    failed_attempts = case when failed_attempts + 1 >= 5 then 0 else failed_attempts + 1 end,
    consecutive_lockouts = case when failed_attempts + 1 >= 5 then consecutive_lockouts + 1 else consecutive_lockouts end,
    locked_until = case when failed_attempts + 1 >= 5
      then now() + interval '15 minutes' * power(2, least(consecutive_lockouts, 10)) else locked_until end
  where id
$$;

-- Every error a browser token can cause has SQLSTATE 28000, which PostgREST maps to 403.
create or replace function yogurt_private.yogurt_check_token(token text) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  found_id bigint;
begin
  update public.yogurt_browsers set last_used_at = now()
  where token_hash = sha256(convert_to(coalesce(token, ''), 'UTF8')) and expires_at > now()
  returning id into found_id;
  if found_id is null then
    raise exception 'invalid or expired browser token' using errcode = '28000';
  end if;
  return found_id;
end $$;

-- Helpers the insert policies call. Policy subqueries run as the caller, who has no select, so the lookups happen here.

create or replace function yogurt_private.yogurt_is_owner() returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  o public.yogurt_owner;
begin
  if uid is null then return false; end if;
  select * into o from public.yogurt_owner;
  if not found then return false; end if;
  if o.user_id is not null then return o.user_id = uid; end if;
  if exists (
    select from auth.users u
    where u.id = uid and u.email_confirmed_at is not null and lower(u.email) = lower(o.email)
  ) then
    update public.yogurt_owner set user_id = uid where user_id is null;
    return (select user_id from public.yogurt_owner) = uid;
  end if;
  return false;
end $$;

create or replace function yogurt_private.yogurt_owns_device(device uuid) returns boolean
language sql security definer set search_path = '' as $$
  select exists (select from public.yogurt_devices d where d.id = device and d.user_id = auth.uid())
$$;

-- A version can only join a push of its own device from the last hour, so a compromised laptop cannot change what an older push shows.
create or replace function yogurt_private.yogurt_push_open(push bigint, device uuid) returns boolean
language sql security definer set search_path = '' as $$
  select exists (
    select from public.yogurt_pushes p
    where p.id = push and p.device_id = device and p.user_id = auth.uid() and p.pushed_at > now() - interval '1 hour'
  )
$$;

create or replace function yogurt_private.yogurt_require_owner() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not yogurt_private.yogurt_is_owner() then
    raise exception 'not the owner' using errcode = '42501';
  end if;
end $$;

-- RPCs

create or replace function public.yogurt_status() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  o public.yogurt_owner;
  mine boolean := yogurt_private.yogurt_is_owner();
begin
  select * into o from public.yogurt_owner;
  return jsonb_build_object(
    'owner_email_set', found,
    'is_owner', mine,
    'passcode_set', mine and o.passcode_hash is not null,
    'locked_until', case when mine and o.locked_until > now() then o.locked_until end
  );
end $$;

-- Five consecutive wrong tries across unlock and set_passcode lock both for 15 minutes, doubling each time up to 2^10 times, until a correct passcode resets it.
-- Returns false for a wrong old passcode or during a lockout. A raised error would roll back the failure count.
create or replace function public.yogurt_set_passcode(new_passcode text, old_passcode text default null) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  o public.yogurt_owner;
begin
  perform yogurt_private.yogurt_require_owner();
  if new_passcode is null or new_passcode !~ '^([0-9]{4}|[0-9]{6})$' then
    raise exception 'passcode must be 4 or 6 digits' using errcode = '22023';
  end if;
  select * into o from public.yogurt_owner for update;
  if o.locked_until > now() then return false; end if;
  if o.passcode_hash is not null
     and (old_passcode is null or extensions.crypt(old_passcode, o.passcode_hash) <> o.passcode_hash) then
    perform yogurt_private.yogurt_note_failure();
    return false;
  end if;
  update public.yogurt_owner
  set passcode_hash = extensions.crypt(new_passcode, extensions.gen_salt('bf')), failed_attempts = 0, consecutive_lockouts = 0, locked_until = null
  where id;
  delete from public.yogurt_browsers where true;
  return true;
end $$;

-- Returns null on a wrong passcode, during a lockout, or before a passcode exists. It never raises for those, so the failure count commits.
create or replace function public.yogurt_unlock(passcode text, remember boolean default false, label text default '') returns text
language plpgsql security definer set search_path = '' as $$
declare
  o public.yogurt_owner;
  token text;
begin
  perform yogurt_private.yogurt_require_owner();
  select * into o from public.yogurt_owner for update;
  if o.passcode_hash is null or o.locked_until > now() then return null; end if;
  if passcode is null or extensions.crypt(passcode, o.passcode_hash) <> o.passcode_hash then
    perform yogurt_private.yogurt_note_failure();
    return null;
  end if;
  update public.yogurt_owner set failed_attempts = 0, consecutive_lockouts = 0, locked_until = null where id;
  delete from public.yogurt_browsers where expires_at < now();
  token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into public.yogurt_browsers (token_hash, label, expires_at)
  values (
    sha256(convert_to(token, 'UTF8')),
    left(coalesce(label, ''), 100),
    now() + case when coalesce(remember, false) then interval '90 days' else interval '12 hours' end
  );
  return token;
end $$;

create or replace function public.yogurt_lock(token text) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  perform yogurt_private.yogurt_require_owner();
  delete from public.yogurt_browsers where token_hash = sha256(convert_to(coalesce(token, ''), 'UTF8'));
  return found;
end $$;

create or replace function public.yogurt_forget_browser(token text, browser_id bigint) returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  delete from public.yogurt_browsers where id = browser_id;
  return found;
end $$;

create or replace function public.yogurt_browsers(token text)
returns table (id bigint, label text, created_at timestamptz, expires_at timestamptz, last_used_at timestamptz, current boolean)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
declare
  me bigint;
begin
  perform yogurt_private.yogurt_require_owner();
  me := yogurt_private.yogurt_check_token(token);
  return query
    select b.id, b.label, b.created_at, b.expires_at, b.last_used_at, b.id = me
    from public.yogurt_browsers b where b.expires_at > now() order by b.id;
end $$;

create or replace function public.yogurt_start_push(device_id uuid) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  new_id bigint;
begin
  perform yogurt_private.yogurt_require_owner();
  if not exists (select from public.yogurt_owner where passcode_hash is not null) then
    raise exception 'choose a passcode in the webapp first' using errcode = 'PT412';
  end if;
  if not yogurt_private.yogurt_owns_device($1) then
    raise exception 'unknown device' using errcode = 'PT404';
  end if;
  insert into public.yogurt_pushes (device_id) values ($1) returning id into new_id;
  return new_id;
end $$;

create or replace function public.yogurt_device_meetings(device_id uuid) returns setof text
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  if not yogurt_private.yogurt_owns_device($1) then
    raise exception 'unknown device' using errcode = 'PT404';
  end if;
  return query
    select l.meeting_id from (
      select distinct on (v.meeting_id) v.meeting_id, v.body
      from public.yogurt_versions v
      where v.device_id = $1 and v.user_id = auth.uid()
      order by v.meeting_id, v.push_id desc
    ) l
    where l.body is not null order by l.meeting_id;
end $$;

-- The latest version of each live meeting per device at or before at_push, or now when null.
create or replace function public.yogurt_library(token text, at_push bigint default null)
returns table (device_id uuid, push_id bigint, pushed_at timestamptz, meeting_id text, body jsonb)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  return query
    select l.device_id, l.push_id, l.pushed_at, l.meeting_id, l.body from (
      select distinct on (v.device_id, v.meeting_id) v.device_id, v.push_id, p.pushed_at, v.meeting_id, v.body
      from public.yogurt_versions v join public.yogurt_pushes p on p.id = v.push_id
      where v.user_id = auth.uid() and (at_push is null or v.push_id <= at_push)
      order by v.device_id, v.meeting_id, v.push_id desc
    ) l
    where l.body is not null order by l.meeting_id, l.device_id;
end $$;

create or replace function public.yogurt_history(token text)
returns table (push_id bigint, device_id uuid, device_name text, pushed_at timestamptz, changed bigint, deleted bigint)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  return query
    select p.id, p.device_id, d.name, p.pushed_at,
           count(v.body), count(*) filter (where v.body is null)
    from public.yogurt_pushes p
    join public.yogurt_versions v on v.push_id = p.id
    join public.yogurt_devices d on d.id = p.device_id
    where p.user_id = auth.uid()
    group by p.id, d.name
    order by p.id desc;
end $$;

create or replace function public.yogurt_device_list(token text)
returns table (id uuid, name text, created_at timestamptz)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform yogurt_private.yogurt_require_owner();
  perform yogurt_private.yogurt_check_token(token);
  return query
    select d.id, d.name, d.created_at from public.yogurt_devices d where d.user_id = auth.uid() order by d.created_at, d.id;
end $$;

-- Row security backs the grants up.
alter table public.yogurt_owner    enable row level security;
alter table public.yogurt_browsers enable row level security;
alter table public.yogurt_devices  enable row level security;
alter table public.yogurt_pushes   enable row level security;
alter table public.yogurt_versions enable row level security;

-- Only devices and versions are insertable. Pushes start through yogurt_start_push, because insert ... returning needs select.
drop policy if exists add on public.yogurt_devices;
create policy add on public.yogurt_devices for insert to authenticated
  with check (user_id = (select auth.uid()) and (select yogurt_private.yogurt_is_owner()));
drop policy if exists add on public.yogurt_versions;
create policy add on public.yogurt_versions for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and (select yogurt_private.yogurt_is_owner())
    and (select yogurt_private.yogurt_push_open(push_id, device_id))
  );

-- Grants are explicit because Supabase no longer grants new public tables to the API roles, and TRUNCATE is outside RLS.
revoke all on public.yogurt_owner, public.yogurt_browsers, public.yogurt_devices, public.yogurt_pushes, public.yogurt_versions
  from public, anon, authenticated;
revoke all on sequence public.yogurt_browsers_id_seq, public.yogurt_pushes_id_seq from public, anon, authenticated;
grant insert (id, name) on public.yogurt_devices to authenticated;
grant insert (meeting_id, push_id, device_id, body) on public.yogurt_versions to authenticated;

-- Execute is revoked everywhere first, so a new or dropped function is never granted by default.
do $$
declare
  f regprocedure;
begin
  for f in select p.oid::regprocedure from pg_proc p
           where p.pronamespace = 'public'::regnamespace and p.proname like 'yogurt\_%' loop
    execute format('revoke execute on function %s from public, anon, authenticated', f);
  end loop;
end $$;
revoke all on schema yogurt_private from public, anon;
revoke execute on all functions in schema yogurt_private from public, anon, authenticated;

grant execute on function
  public.yogurt_status(),
  public.yogurt_set_passcode(text, text),
  public.yogurt_unlock(text, boolean, text),
  public.yogurt_lock(text),
  public.yogurt_forget_browser(text, bigint),
  public.yogurt_browsers(text),
  public.yogurt_start_push(uuid),
  public.yogurt_device_meetings(uuid),
  public.yogurt_library(text, bigint),
  public.yogurt_history(text),
  public.yogurt_device_list(text)
to authenticated;

